const runtimeProtoPath = "daemon/runtime_config.proto"

var runtimeProtoOutputs = []string{"daemon/runtime_config.pb.go", "daemon/runtime_config_grpc.pb.go"}

var runtimeProtoc = struct {
	URL            string `json:"url"`
	Asset          string `json:"asset"`
	SHA256         string `json:"sha256"`
	Bytes          int64  `json:"bytes"`
	ChecksumSource string `json:"checksumSource"`
}{
	"https://github.com/protocolbuffers/protobuf/releases/download/v21.12/protoc-21.12-linux-x86_64.zip",
	"https://api.github.com/repos/protocolbuffers/protobuf/releases/assets/88187108",
	"3a4c1e5f2516c639d3079b1586e703fc7bcfa2136d58bda24d1d54f949c315e8", 1585982,
	// This historical asset has no release API digest; Google's pinned consumer records it.
	"https://skia.googlesource.com/buildbot/+/e4cf17db6917/WORKSPACE",
}

var protoPlugins = []string{
	"google.golang.org/protobuf/cmd/protoc-gen-go@v1.36.11",
	"google.golang.org/grpc/cmd/protoc-gen-go-grpc@v1.5.1",
}

var protoToolVersions = map[string]string{
	"protoc": "libprotoc 3.21.12", "protoc-gen-go": "protoc-gen-go v1.36.11", "protoc-gen-go-grpc": "protoc-gen-go-grpc 1.5.1",
}

var protocMembers = []string{"bin/protoc", "include/google/protobuf/empty.proto"}

func extractProtoc(data []byte, destination string) error {
	if int64(len(data)) != runtimeProtoc.Bytes || sha256Hex(data) != runtimeProtoc.SHA256 {
		return fmt.Errorf("official protoc archive size or SHA256 differs from the reviewed pin")
	}
	archive, err := zip.NewReader(bytes.NewReader(data), int64(len(data)))
	if err != nil {
		return err
	}
	for _, name := range protocMembers {
		var member *zip.File
		for _, entry := range archive.File {
			if entry.Name == name {
				if member != nil {
					return fmt.Errorf("duplicate protoc archive entry: %s", name)
				}
				member = entry
			}
		}
		if member == nil || !member.Mode().IsRegular() {
			return fmt.Errorf("missing or non-regular protoc archive entry: %s", name)
		}
		input, err := member.Open()
		if err != nil {
			return err
		}
		contents, err := io.ReadAll(input)
		closeErr := input.Close()
		if err != nil || closeErr != nil {
			return errors.Join(err, closeErr)
		}
		filename := filepath.Join(destination, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(filename), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(filename, contents, 0o644); err != nil {
			return err
		}
	}
	return os.Chmod(filepath.Join(destination, "bin/protoc"), 0o700)
}

func runtimeGenerated(directory string, checkedRoot string) (map[string]any, error) {
	actual := map[string]bool{}
	if err := filepath.WalkDir(directory, func(filename string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.Type()&os.ModeSymlink != 0 {
			return fmt.Errorf("symlink in generated-source output")
		}
		if entry.Type().IsRegular() {
			name, err := filepath.Rel(directory, filename)
			if err != nil {
				return err
			}
			actual[filepath.ToSlash(name)] = true
		}
		return nil
	}); err != nil {
		return nil, err
	}
	if len(actual) != len(runtimeProtoOutputs) {
		return nil, fmt.Errorf("generation must produce exactly the two runtime-config Go files")
	}
	result := map[string]any{}
	for _, name := range runtimeProtoOutputs {
		if !actual[name] {
			return nil, fmt.Errorf("missing generated runtime protobuf: %s", name)
		}
		data, err := os.ReadFile(filepath.Join(directory, filepath.FromSlash(name)))
		if err != nil {
			return nil, err
		}
		if !bytes.HasPrefix(data, []byte("// Code generated by protoc-gen-go")) {
			return nil, fmt.Errorf("generated header is missing: %s", name)
		}
		if checkedRoot != "" {
			filename, err := regularSource(checkedRoot, name)
			if err != nil {
				return nil, err
			}
			checked, err := os.ReadFile(filename)
			if err != nil {
				return nil, err
			}
			if !bytes.Equal(checked, data) {
				return nil, fmt.Errorf("checked-in runtime protobuf differs: %s", name)
			}
		}
		result[name] = map[string]any{"sha256": sha256Hex(data), "bytes": len(data)}
	}
	return result, nil
}

func outsideSource(root, name string) (string, error) {
	if !filepath.IsAbs(name) || filepath.Clean(name) != name {
		return "", fmt.Errorf("tool and artifact directories must be absolute without traversal or aliases")
	}
	// The fresh artifact directory may not exist yet. Resolve its existing parent
	// to reject aliases without creating anything in the source checkout.
	parent := name
	var missing []string
	for {
		_, err := os.Lstat(parent)
		if err == nil {
			break
		}
		if !os.IsNotExist(err) {
			return "", err
		}
		missing = append(missing, filepath.Base(parent))
		parent = filepath.Dir(parent)
	}
	resolved, err := filepath.EvalSymlinks(parent)
	if err != nil {
		return "", err
	}
	for i := len(missing) - 1; i >= 0; i-- {
		resolved = filepath.Join(resolved, missing[i])
	}
	if resolved != name {
		return "", fmt.Errorf("tool and artifact directories must not use aliases")
	}
	relative, err := filepath.Rel(root, name)
	if err != nil || relative != ".." && !strings.HasPrefix(relative, ".."+string(filepath.Separator)) {
		return "", fmt.Errorf("tool and artifact directories must be outside the source checkout")
	}
	return name, nil
}

func runtimeProtoIdentity(root string) (map[string]any, error) {
	if os.Getenv("GITHUB_ACTIONS") != "true" || os.Getenv("GITHUB_REPOSITORY") != "polaris-arch/sing-box-polaris" ||
		os.Getenv("RUNNER_ENVIRONMENT") != "github-hosted" || os.Getenv("RUNNER_OS") != "Linux" ||
		runtime.GOOS != "linux" || runtime.GOARCH != "amd64" {
		return nil, fmt.Errorf("scoped protobuf generation requires the project GitHub-hosted Linux x64 runner")
	}
	source, err := git(root, "rev-parse", "HEAD")
	if err != nil {
		return nil, err
	}
	if strings.TrimSpace(string(source)) != os.Getenv("GITHUB_SHA") {
		return nil, fmt.Errorf("source differs from the exact workflow commit")
	}
	status, err := git(root, "status", "--porcelain", "--untracked-files=all")
	if err != nil {
		return nil, err
	}
	if len(bytes.TrimSpace(status)) != 0 {
		return nil, fmt.Errorf("scoped generation requires an unchanged, clean checkout")
	}
	tree, err := git(root, "rev-parse", "HEAD^{tree}")
	if err != nil {
		return nil, err
	}
	identity := map[string]any{"sourceCommit": strings.TrimSpace(string(source)), "sourceTree": strings.TrimSpace(string(tree))}
	for field, key := range map[string]string{"workflowRun": "GITHUB_RUN_ID", "workflowAttempt": "GITHUB_RUN_ATTEMPT"} {
		identity[field] = nil
		if value, ok := os.LookupEnv(key); ok {
			identity[field] = value
		}
	}
	return identity, nil
}

func runtimeProto(args []string) (err error) {
	if len(args) == 0 || args[0] != "generate" && args[0] != "check" {
		return fmt.Errorf("runtime-proto requires generate or check and --output")
	}
	mode := args[0]
	flags := flag.NewFlagSet("runtime-proto", flag.ContinueOnError)
	outputArg := flags.String("output", "", "fresh artifact directory in runner temporary storage")
	if err := flags.Parse(args[1:]); err != nil {
		return err
	}
	if *outputArg == "" || flags.NArg() != 0 {
		return fmt.Errorf("runtime-proto requires --output and no extra arguments")
	}
	root, err := os.Getwd()
	if err != nil {
		return err
	}
	root, err = filepath.EvalSymlinks(root)
	if err != nil {
		return err
	}
	identity, err := runtimeProtoIdentity(root)
	if err != nil {
		return err
	}
	output, err := outsideSource(root, *outputArg)
	if err != nil {
		return err
	}
	if _, err := os.Lstat(output); !os.IsNotExist(err) {
		return fmt.Errorf("artifact directory must be fresh: %v", err)
	}
	scratch, err := outsideSource(root, os.Getenv("RUNNER_TEMP"))
	if err != nil {
		return err
	}
	if !strings.HasPrefix(output, scratch+string(filepath.Separator)) {
		return fmt.Errorf("artifact directory must be a fresh child of runner temporary storage")
	}
	env := append(os.Environ(), "GOTOOLCHAIN=local", "GOWORK=off", "GOENV=off", "GOFLAGS=-mod=readonly",
		"GOSUMDB=sum.golang.org", "GOPROXY=https://proxy.golang.org", "GOPRIVATE=", "GONOSUMDB=", "GONOPROXY=", "GOINSECURE=")
	goVersion, err := pinnedGoVersion(root, env)
	if err != nil {
		return err
	}
	protoPath, err := regularSource(root, runtimeProtoPath)
	if err != nil {
		return err
	}
	proto, err := os.ReadFile(protoPath)
	if err != nil {
		return err
	}
	work, err := os.MkdirTemp(scratch, "runtime-proto-")
	if err != nil {
		return err
	}
	defer func() { err = errors.Join(err, os.RemoveAll(work)) }()
	tools, generated := filepath.Join(work, "tools"), filepath.Join(work, "generated")
	if err := os.Mkdir(generated, 0o700); err != nil {
		return err
	}
	client := &http.Client{Timeout: 120 * time.Second}
	response, err := client.Get(runtimeProtoc.URL)
	if err != nil {
		return err
	}
	archive, readErr := io.ReadAll(io.LimitReader(response.Body, runtimeProtoc.Bytes+1))
	closeErr := response.Body.Close()
	if readErr != nil || closeErr != nil {
		return errors.Join(readErr, closeErr)
	}
	if response.StatusCode != http.StatusOK || response.Request.URL.Scheme != "https" {
		return fmt.Errorf("official protoc download failed or redirected insecurely")
	}
	if err := extractProtoc(archive, tools); err != nil {
		return err
	}
	env = append(env, "GOBIN="+filepath.Join(tools, "bin"))
	run := func(timeout time.Duration, directory string, args ...string) error {
		ctx, cancel := context.WithTimeout(context.Background(), timeout)
		defer cancel()
		command := exec.CommandContext(ctx, args[0], args[1:]...)
		command.Dir, command.Env = directory, env
		command.Stdout, command.Stderr = os.Stdout, os.Stderr
		return command.Run()
	}
	for _, plugin := range protoPlugins {
		if err := run(600*time.Second, work, "go", "install", plugin); err != nil {
			return err
		}
	}
	toolReceipts := map[string]any{}
	for name, expected := range protoToolVersions {
		tool := filepath.Join(tools, "bin", name)
		ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		command := exec.CommandContext(ctx, tool, "--version")
		command.Dir, command.Env, command.Stderr = work, env, os.Stderr
		version, err := command.Output()
		cancel()
		if err != nil {
			return err
		}
		if strings.TrimSpace(string(version)) != expected {
			return fmt.Errorf("generator version differs: %s", name)
		}
		hash, err := fileSHA256(tool)
		if err != nil {
			return err
		}
		toolReceipts[name] = map[string]any{"version": expected, "sha256": hash}
	}
	if err := run(120*time.Second, root, filepath.Join(tools, "bin/protoc"), "-I", ".", "-I", filepath.Join(tools, "include"),
		"--go_out="+generated, "--go_opt=paths=source_relative", "--go-grpc_out="+generated, "--go-grpc_opt=paths=source_relative",
		"--plugin=protoc-gen-go="+filepath.Join(tools, "bin/protoc-gen-go"),
		"--plugin=protoc-gen-go-grpc="+filepath.Join(tools, "bin/protoc-gen-go-grpc"), runtimeProtoPath); err != nil {
		return err
	}
	checkedRoot := ""
	if mode == "check" {
		checkedRoot = root
	}
	inventory, err := runtimeGenerated(generated, checkedRoot)
	if err != nil {
		return err
	}
	currentProto, err := os.ReadFile(protoPath)
	if err != nil {
		return err
	}
	currentIdentity, err := runtimeProtoIdentity(root)
	if err != nil {
		return err
	}
	if !bytes.Equal(proto, currentProto) || !reflect.DeepEqual(identity, currentIdentity) {
		return fmt.Errorf("source identity changed during generation")
	}
	wellKnown, err := fileSHA256(filepath.Join(tools, filepath.FromSlash(protocMembers[1])))
	if err != nil {
		return err
	}
	receipt := map[string]any{
		"schema": "polaris-runtime-protobuf-v1", "mode": mode, "goVersion": goVersion,
		"input": map[string]any{"path": runtimeProtoPath, "sha256": sha256Hex(proto)}, "protocArchive": runtimeProtoc,
		"tools": toolReceipts, "pluginModules": protoPlugins,
		"wellKnownInput": map[string]any{"path": protocMembers[1], "sha256": wellKnown},
		"outputs":        inventory, "checkedInEquality": mode == "check", "nativeValidationPerformed": false,
	}
	for key, value := range identity {
		receipt[key] = value
	}
	if err := os.MkdirAll(filepath.Dir(output), 0o755); err != nil {
		return err
	}
	if err := os.Mkdir(output, 0o755); err != nil {
		return err
	}
	for _, name := range runtimeProtoOutputs {
		target := filepath.Join(output, filepath.FromSlash(name))
		data, err := os.ReadFile(filepath.Join(generated, filepath.FromSlash(name)))
		if err != nil {
			return err
		}
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(target, data, 0o644); err != nil {
			return err
		}
	}
	if err := writeJSONFile(filepath.Join(output, "receipt.json"), receipt); err != nil {
		return err
	}
	return writeJSON(os.Stdout, receipt)
}
