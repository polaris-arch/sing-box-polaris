"""Generate or check only the additive runtime-config protobuf in remote CI."""
import argparse
import hashlib
import io
import json
import os
from pathlib import Path
import platform
import shutil
import stat
import subprocess
import tempfile
import urllib.request
import zipfile


ROOT = Path(__file__).resolve().parents[2]
PROTO = 'daemon/runtime_config.proto'
OUTPUTS = ('daemon/runtime_config.pb.go', 'daemon/runtime_config_grpc.pb.go')
PROTOC_URL = ('https://github.com/protocolbuffers/protobuf/releases/download/'
              'v21.12/protoc-21.12-linux-x86_64.zip')
PROTOC_SHA256 = '3a4c1e5f2516c639d3079b1586e703fc7bcfa2136d58bda24d1d54f949c315e8'
PROTOC_BYTES = 1585982
# The upstream release API has digest=null for this historical asset.
# Google's source-pinned consumer records this digest for the official URL.
CHECKSUM_SOURCE = 'https://skia.googlesource.com/buildbot/+/e4cf17db6917/WORKSPACE'
PROTOC_ASSET = 'https://api.github.com/repos/protocolbuffers/protobuf/releases/assets/88187108'
VERSIONS = {
    'protoc': 'libprotoc 3.21.12',
    'protoc-gen-go': 'protoc-gen-go v1.36.11',
    'protoc-gen-go-grpc': 'protoc-gen-go-grpc 1.5.1',
}
PLUGINS = (
    'google.golang.org/protobuf/cmd/protoc-gen-go@v1.36.11',
    'google.golang.org/grpc/cmd/protoc-gen-go-grpc@v1.5.1',
)
ARCHIVE_MEMBERS = ('bin/protoc', 'include/google/protobuf/empty.proto')


def digest(data):
    return hashlib.sha256(data).hexdigest()


def verify_archive(data):
    if len(data) != PROTOC_BYTES or digest(data) != PROTOC_SHA256:
        raise ValueError('official protoc archive size or SHA256 differs from the reviewed pin')


def extract_tools(data, destination):
    """Extract two fixed regular entries, never arbitrary ZIP paths."""
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        names = archive.namelist()
        for name in ARCHIVE_MEMBERS:
            if names.count(name) != 1:
                raise ValueError('missing or duplicate protoc archive entry: ' + name)
            info = archive.getinfo(name)
            kind = stat.S_IFMT(info.external_attr >> 16)
            if info.is_dir() or kind not in (0, stat.S_IFREG):
                raise ValueError('non-regular protoc archive entry: ' + name)
            path = destination / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(archive.read(info))
    (destination / 'bin/protoc').chmod(0o700)


def generation_command(tools, destination):
    return [
        str(tools / 'bin/protoc'), '-I', '.',
        '-I', str(tools / 'include'),
        '--go_out=' + str(destination), '--go_opt=paths=source_relative',
        '--go-grpc_out=' + str(destination), '--go-grpc_opt=paths=source_relative',
        '--plugin=protoc-gen-go=' + str(tools / 'bin/protoc-gen-go'),
        '--plugin=protoc-gen-go-grpc=' + str(tools / 'bin/protoc-gen-go-grpc'),
        PROTO,
    ]


def generated_inventory(directory):
    paths = list(directory.rglob('*'))
    if any(path.is_symlink() for path in paths):
        raise ValueError('symlink in generated-source output')
    actual = {path.relative_to(directory).as_posix() for path in paths if path.is_file()}
    if actual != set(OUTPUTS):
        raise ValueError('generation must produce exactly the two runtime-config Go files')
    result = {}
    for name in OUTPUTS:
        data = (directory / name).read_bytes()
        if not data.startswith(b'// Code generated by protoc-gen-go'):
            raise ValueError('generated header is missing: ' + name)
        result[name] = {'sha256': digest(data), 'bytes': len(data)}
    return result


def compare_generated(directory, root):
    for name in OUTPUTS:
        path = root / name
        if path.is_symlink() or not path.is_file():
            raise ValueError('checked-in generated file is missing or unsafe: ' + name)
        if path.read_bytes() != (directory / name).read_bytes():
            raise ValueError('checked-in runtime protobuf differs: ' + name)


def outside_source(path):
    path = Path(path)
    if not path.is_absolute() or '..' in path.parts or path.resolve() != path:
        raise ValueError('tool and artifact directories must be absolute paths without traversal or aliases')
    if path == ROOT or ROOT in path.parents:
        raise ValueError('tool and artifact directories must be outside the source checkout')
    return path


def source_identity(env):
    if (env.get('GITHUB_ACTIONS') != 'true'
            or env.get('GITHUB_REPOSITORY') != 'polaris-arch/sing-box-polaris'
            or env.get('RUNNER_ENVIRONMENT') != 'github-hosted'
            or env.get('RUNNER_OS') != 'Linux'
            or platform.system() != 'Linux'
            or platform.machine() != 'x86_64'):
        raise ValueError('scoped protobuf generation requires the project GitHub-hosted Linux x64 runner')
    source = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    if source != env.get('GITHUB_SHA'):
        raise ValueError('source differs from the exact workflow commit')
    if subprocess.check_output(['git', 'status', '--porcelain', '--untracked-files=all'],
                               cwd=ROOT, text=True).strip():
        raise ValueError('scoped generation requires an unchanged, clean checkout')
    tree = subprocess.check_output(['git', 'rev-parse', 'HEAD^{tree}'], cwd=ROOT, text=True).strip()
    return {'sourceCommit': source, 'sourceTree': tree,
            'workflowRun': env.get('GITHUB_RUN_ID'), 'workflowAttempt': env.get('GITHUB_RUN_ATTEMPT')}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('mode', choices=('generate', 'check'))
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    env = dict(os.environ, GOTOOLCHAIN='local', GOWORK='off', GOENV='off', GOFLAGS='-mod=readonly',
               GOSUMDB='sum.golang.org', GOPROXY='https://proxy.golang.org',
               GOPRIVATE='', GONOSUMDB='', GONOPROXY='', GOINSECURE='')
    identity = source_identity(env)
    output = outside_source(args.output)
    if output.exists():
        raise ValueError('artifact directory must be fresh')
    scratch = outside_source(Path(env['RUNNER_TEMP']))
    if scratch not in output.parents:
        raise ValueError('artifact directory must be a fresh child of runner temporary storage')
    required_go = 'go' + (ROOT / 'release/GO_VERSION').read_text().strip()
    actual_go = subprocess.check_output(['go', 'env', 'GOVERSION'], env=env, text=True).strip()
    if required_go != 'go1.27.2' or actual_go != required_go:
        raise ValueError('scoped generation requires the reviewed Go 1.27.2 pin')
    proto_path = ROOT / PROTO
    if proto_path.is_symlink() or proto_path.resolve() != proto_path or not proto_path.is_file():
        raise ValueError('runtime proto input must be the checked-in regular source file')
    proto = proto_path.read_bytes()
    with tempfile.TemporaryDirectory(prefix='runtime-proto-', dir=scratch) as temporary:
        work = Path(temporary)
        tools = work / 'tools'
        generated = work / 'generated'
        generated.mkdir()
        with urllib.request.urlopen(PROTOC_URL, timeout=120) as response:
            if not response.url.startswith('https://'):
                raise ValueError('insecure protoc archive redirect')
            archive = response.read(PROTOC_BYTES + 1)
        verify_archive(archive)
        extract_tools(archive, tools)
        env['GOBIN'] = str(tools / 'bin')
        for plugin in PLUGINS:
            subprocess.run(['go', 'install', plugin], cwd=work, env=env, check=True, timeout=600)
        versions = {}
        tool_hashes = {}
        for name, expected in VERSIONS.items():
            tool = tools / 'bin' / name
            version = subprocess.check_output([str(tool), '--version'], env=env,
                                              text=True, timeout=30).strip()
            if version != expected:
                raise ValueError('generator version differs: ' + name)
            versions[name] = version
            tool_hashes[name] = digest(tool.read_bytes())
        command = generation_command(tools, generated)
        subprocess.run(command, cwd=ROOT, env=env, check=True, timeout=120)
        inventory = generated_inventory(generated)
        if args.mode == 'check':
            compare_generated(generated, ROOT)
        if (ROOT / PROTO).read_bytes() != proto or source_identity(env) != identity:
            raise ValueError('source identity changed during generation')
        receipt = {
            'schema': 'polaris-runtime-protobuf-v1', **identity, 'mode': args.mode,
            'goVersion': actual_go, 'input': {'path': PROTO, 'sha256': digest(proto)},
            'protocArchive': {'url': PROTOC_URL, 'asset': PROTOC_ASSET,
                             'sha256': PROTOC_SHA256, 'bytes': PROTOC_BYTES,
                             'checksumSource': CHECKSUM_SOURCE},
            'tools': {name: {'version': versions[name], 'sha256': tool_hashes[name]}
                      for name in VERSIONS},
            'pluginModules': list(PLUGINS),
            'wellKnownInput': {'path': ARCHIVE_MEMBERS[1],
                              'sha256': digest((tools / ARCHIVE_MEMBERS[1]).read_bytes())},
            'outputs': inventory, 'checkedInEquality': args.mode == 'check',
            'nativeValidationPerformed': False,
        }
        output.mkdir(parents=True)
        for name in OUTPUTS:
            target = output / name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(generated / name, target)
        (output / 'receipt.json').write_text(json.dumps(receipt, indent=2, sort_keys=True) + '\n')
        print(json.dumps(receipt, sort_keys=True))


if __name__ == '__main__':
    main()
