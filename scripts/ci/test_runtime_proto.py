"""Pure scoped-generation controls; no compiler, generator or network execution."""
import io
from pathlib import Path
import stat
import tempfile
import unittest
from unittest.mock import patch
import zipfile

import runtime_proto as subject


class RuntimeProtoControls(unittest.TestCase):
    def test_exact_tool_versions_and_single_proto_command(self):
        self.assertEqual(subject.VERSIONS, {
            'protoc': 'libprotoc 3.21.12',
            'protoc-gen-go': 'protoc-gen-go v1.36.11',
            'protoc-gen-go-grpc': 'protoc-gen-go-grpc 1.5.1',
        })
        self.assertEqual(subject.PLUGINS, (
            'google.golang.org/protobuf/cmd/protoc-gen-go@v1.36.11',
            'google.golang.org/grpc/cmd/protoc-gen-go-grpc@v1.5.1',
        ))
        command = subject.generation_command(Path('/tools'), Path('/output'))
        self.assertEqual([x for x in command if x.endswith('.proto')],
                         ['daemon/runtime_config.proto'])
        self.assertIn('--go_opt=paths=source_relative', command)
        self.assertIn('--go-grpc_opt=paths=source_relative', command)
        self.assertIn('--go_out=/output', command)
        self.assertNotIn('@latest', ' '.join(command + list(subject.PLUGINS)))

    def test_archive_requires_both_reviewed_size_and_digest(self):
        data = b'fixture'
        with patch.object(subject, 'PROTOC_BYTES', len(data)), \
                patch.object(subject, 'PROTOC_SHA256', subject.digest(data)):
            subject.verify_archive(data)
            for changed in (b'fixturf', data + b'x', data[:-1]):
                with self.subTest(changed=changed), self.assertRaises(ValueError):
                    subject.verify_archive(changed)

    def archive(self, entries):
        stream = io.BytesIO()
        with zipfile.ZipFile(stream, 'w') as archive:
            for name, mode in entries:
                info = zipfile.ZipInfo(name)
                info.external_attr = mode << 16
                archive.writestr(info, b'fixture')
        return stream.getvalue()

    def test_extraction_is_limited_to_two_fixed_regular_members(self):
        entries = [(name, stat.S_IFREG | 0o644) for name in subject.ARCHIVE_MEMBERS]
        entries.append(('../unrequested', stat.S_IFREG | 0o644))
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory) / 'tools'
            subject.extract_tools(self.archive(entries), root)
            self.assertEqual({p.relative_to(root).as_posix() for p in root.rglob('*') if p.is_file()},
                             set(subject.ARCHIVE_MEMBERS))
            self.assertFalse((Path(directory) / 'unrequested').exists())
        for entries in ([(subject.ARCHIVE_MEMBERS[0], stat.S_IFLNK | 0o777)],
                        [(subject.ARCHIVE_MEMBERS[0], stat.S_IFREG | 0o644)]):
            with tempfile.TemporaryDirectory() as directory, self.assertRaises(ValueError):
                subject.extract_tools(self.archive(entries), Path(directory))

    def generated(self, root):
        for name in subject.OUTPUTS:
            path = root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(b'// Code generated by protoc-gen-go. DO NOT EDIT.\npackage daemon\n')

    def test_exact_outputs_headers_and_checked_in_equality(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            generated, checked = root / 'generated', root / 'checked'
            self.generated(generated)
            self.generated(checked)
            inventory = subject.generated_inventory(generated)
            self.assertEqual(set(inventory), set(subject.OUTPUTS))
            subject.compare_generated(generated, checked)
            (checked / subject.OUTPUTS[0]).write_bytes(b'changed')
            with self.assertRaises(ValueError):
                subject.compare_generated(generated, checked)
            (generated / 'unrelated.pb.go').write_bytes(b'unrelated')
            with self.assertRaises(ValueError):
                subject.generated_inventory(generated)
            (generated / 'unrelated.pb.go').unlink()
            (generated / subject.OUTPUTS[0]).write_bytes(b'package daemon\n')
            with self.assertRaises(ValueError):
                subject.generated_inventory(generated)

    def test_missing_output_fails_closed(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            self.generated(root)
            (root / subject.OUTPUTS[1]).unlink()
            with self.assertRaises(ValueError):
                subject.generated_inventory(root)

    def test_generation_rejects_non_ci_before_any_subprocess(self):
        with patch.object(subject.subprocess, 'check_output') as check:
            with self.assertRaises(ValueError):
                subject.source_identity({})
            check.assert_not_called()

    def test_output_cannot_modify_the_source_checkout(self):
        for path in (subject.ROOT, subject.ROOT / 'daemon/generated'):
            with self.subTest(path=path), self.assertRaises(ValueError):
                subject.outside_source(path)

    def test_output_rejects_relative_and_traversal_aliases(self):
        for path in (Path('relative'), Path('/tmp/../aliased')):
            with self.subTest(path=path), self.assertRaises(ValueError):
                subject.outside_source(path)


if __name__ == '__main__':
    unittest.main()
