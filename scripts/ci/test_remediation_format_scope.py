"""Exercise formatter scope and fixed-point checking without native tools."""
import contextlib
import io
import json
import os
from pathlib import Path
import runpy
import subprocess
import tempfile
from types import SimpleNamespace
import unittest
from unittest.mock import patch

SCRIPT = Path(__file__).with_name('check_remediation_format.py').resolve()
TOOL = '/pinned/golangci-lint'


class FormatScopeTests(unittest.TestCase):
    def check_scope(self, extra=(), transform=None, fixtures=None, version_code=0, setup=None, tool=TOOL):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            content = {
                'old.go': b'package fixture\n',
                'new.go': b'package fixture\n',
                '.golangci.yml': b'version: "2"\nformatters:\n  enable: [gci, gofumpt]\n',
                'go.mod': b'module fixture\n\ngo 1.27.0\nreplace dependency => ./third_party/dependency\n',
                'go.sum': b'module-checksum-context\n',
                'go.work': b'go 1.27.0\nuse (. ./nested)\n',
                'nested/go.mod': b'module fixture/nested\n',
                'third_party/dependency/go.mod': b'module dependency\n',
                'third_party/dependency/source.go': b'package dependency\n',
                'generated.go': b'// Code generated by fixture. DO NOT EDIT.\npackage fixture\n',
            }
            content.update(fixtures or {})
            for name, value in content.items():
                path = root / name
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(value)
            (root / 'release').mkdir()
            (root / 'release/audit-remediation-source-inventory.json').write_text(json.dumps({
                'schema': 'audit-remediation-source-inventory-v1',
                'files': [{'path': 'old.go'}],
                'dailyHotFormattingScope': {'paths': list(extra)},
            }))
            if setup:
                setup(root)
            before = {p.relative_to(root): p.read_bytes() for p in root.rglob('*') if p.is_file()}
            calls = []
            copies = []

            def execute(command, **kwargs):
                calls.append(command)
                self.assertFalse(kwargs['check'])
                self.assertEqual(kwargs['stdout'], subprocess.PIPE)
                self.assertEqual(kwargs['stderr'], subprocess.PIPE)
                if command[1] == 'version':
                    return subprocess.CompletedProcess(command, version_code, b'pinned version\n', b'')
                copy = Path(kwargs['cwd'])
                copies.append(copy)
                self.assertNotEqual(copy, root)
                self.assertFalse(copy.is_relative_to(root))
                self.assertEqual(command[1:5], ['fmt', '--config', '.golangci.yml', '--'])
                for name in ('.golangci.yml', 'go.mod', 'go.sum', 'go.work', 'nested/go.mod', 'third_party/dependency/go.mod'):
                    self.assertEqual((copy / name).read_bytes(), content[name])
                if transform:
                    result = transform(copy, len(copies), command[5:])
                    if result is not None:
                        return result
                return subprocess.CompletedProcess(command, 0, b'', b'')

            stdout = io.TextIOWrapper(io.BytesIO())
            stderr = io.TextIOWrapper(io.BytesIO())
            previous = Path.cwd()
            exit_code = 0
            try:
                os.chdir(root)
                with patch.dict(os.environ, GOLANGCI_LINT=tool), patch('subprocess.run', execute), contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
                    try:
                        runpy.run_path(str(SCRIPT), run_name='__main__')
                    except SystemExit as exc:
                        exit_code = exc.code
            finally:
                os.chdir(previous)
            stdout.flush()
            stderr.flush()
            result = SimpleNamespace(
                calls=calls, passes=len(copies), exit_code=exit_code,
                stdout=stdout.buffer.getvalue(), stderr=stderr.buffer.getvalue(),
            )
            after = {p.relative_to(root): p.read_bytes() for p in root.rglob('*') if p.is_file()}
            self.assertEqual(before, after, 'The checkout must never be rewritten')
            self.assertTrue(all(not copy.exists() for copy in copies), 'Disposable source copies must be cleaned up')
            return result

    def test_union_deduplicates_and_excludes_dependencies_and_generated_bindings(self):
        result = self.check_scope(['new.go', 'old.go', 'generated.go', 'third_party/native/a.go', './third_party/native/b.go', 'vendor/a.go', 'release/dependency-sources/a.go', 'daemon/api.pb.go'])
        self.assertEqual(result.exit_code, 0)
        self.assertEqual(result.calls[-1], [TOOL, 'fmt', '--config', '.golangci.yml', '--', 'new.go', 'old.go'])
        self.assertEqual(result.passes, 1)
        self.assertIn(b'2 files; vendor/generated excluded', result.stdout)

    def test_missing_owned_path_fails_closed(self):
        result = self.check_scope(['missing.go'])
        self.assertIn('Missing or unsafe', result.exit_code)
        self.assertFalse(result.calls)

    def test_unsafe_path_fails_closed(self):
        for path in ('../outside.go', '/outside.go', 'name\n.go'):
            with self.subTest(path=path):
                result = self.check_scope([path])
                self.assertIn('Invalid inventory path', result.exit_code)
                self.assertFalse(result.calls)

    def test_owned_symlink_and_symlink_parent_fail_closed(self):
        for path in ('alias.go', 'alias/new.go'):
            with self.subTest(path=path):
                def setup(root):
                    (root / 'alias.go').symlink_to(root / 'new.go')
                    (root / 'alias').symlink_to(root, target_is_directory=True)
                result = self.check_scope([path], setup=setup)
                self.assertIn('Missing or unsafe', result.exit_code)
                self.assertFalse(result.calls)

    def test_stable_but_different_output_still_fails_with_exact_final_diff(self):
        final = b'package fixture\n\nvar n = 1\n'
        def transform(copy, number, files):
            (copy / 'old.go').write_bytes(final)
        result = self.check_scope(transform=transform)
        self.assertIn('Owned source formatting differs', result.exit_code)
        self.assertEqual(result.passes, 2)
        self.assertEqual(result.stdout, b'--- a/old.go\n+++ b/old.go\n@@ -1 +1,3 @@\n package fixture\n+\n+var n = 1\n')
        self.assertNotIn(b'pinned version', result.stdout)

    def test_second_pass_change_is_included_only_in_original_to_fixed_point_diff(self):
        def transform(copy, number, files):
            value = b'package intermediate\n' if number == 1 else b'package final\n'
            (copy / 'old.go').write_bytes(value)
        result = self.check_scope(transform=transform)
        self.assertIn('Owned source formatting differs', result.exit_code)
        self.assertEqual(result.passes, 3)
        self.assertEqual(result.stdout, b'--- a/old.go\n+++ b/old.go\n@@ -1 +1 @@\n-package fixture\n+package final\n')
        self.assertNotIn(b'intermediate', result.stdout)

    def test_missing_final_newline_has_an_applicable_unified_diff_marker(self):
        def transform(copy, number, files):
            (copy / 'old.go').write_bytes(b'package fixture\n')
        result = self.check_scope(transform=transform, fixtures={'old.go': b'package fixture'})
        self.assertIn('Owned source formatting differs', result.exit_code)
        self.assertEqual(result.stdout, b'--- a/old.go\n+++ b/old.go\n@@ -1 +1 @@\n-package fixture\n\\ No newline at end of file\n+package fixture\n')

    def test_byte_changes_are_not_hidden_by_newline_normalization(self):
        def transform(copy, number, files):
            (copy / 'old.go').write_bytes(b'package fixture\n')
        result = self.check_scope(transform=transform, fixtures={'old.go': b'package fixture\r\n'})
        self.assertIn('Owned source formatting differs', result.exit_code)
        self.assertIn(b'-package fixture\r\n+package fixture\n', result.stdout)

    def test_nonconvergent_cycle_fails_without_emitting_a_partial_diff(self):
        def transform(copy, number, files):
            (copy / 'old.go').write_bytes(b'package alternating\n' if number % 2 else b'package fixture\n')
        result = self.check_scope(transform=transform)
        self.assertIn('did not reach a byte-stable fixed point after 6 passes', result.exit_code)
        self.assertEqual(result.passes, 6)
        self.assertEqual(result.stdout, b'')

    def test_convergence_at_bound_is_accepted_but_dirty_checkout_still_fails(self):
        def transform(copy, number, files):
            (copy / 'old.go').write_bytes(('package pass' + str(min(number, 5)) + '\n').encode())
        result = self.check_scope(transform=transform)
        self.assertIn('Owned source formatting differs', result.exit_code)
        self.assertEqual(result.passes, 6)
        self.assertIn(b'+package pass5\n', result.stdout)

    def test_nonzero_or_signal_tool_failure_fails_without_partial_diff(self):
        for code in (1, 2, -9):
            with self.subTest(code=code):
                def transform(copy, number, files):
                    (copy / 'old.go').write_bytes(b'package partially_formatted\n')
                    return subprocess.CompletedProcess([], code, b'partial tool stdout\n', b'tool failed\n')
                result = self.check_scope(transform=transform)
                self.assertEqual(result.exit_code, max(code, 1))
                self.assertEqual(result.passes, 1)
                self.assertEqual(result.stdout, b'')
                self.assertIn(b'tool failed', result.stderr)
                self.assertIn(b'partial tool stdout', result.stderr)

    def test_zero_exit_formatter_warning_is_not_mistaken_for_clean(self):
        for stdout, stderr in ((b'', b'WARN (gofumpt) formatting file old.go: parse error\n'), (b'unexpected output\n', b'')):
            with self.subTest(stdout=stdout, stderr=stderr):
                def transform(copy, number, files):
                    return subprocess.CompletedProcess([], 0, stdout, stderr)
                result = self.check_scope(transform=transform)
                self.assertIn('unexpected diagnostics', result.exit_code)
                self.assertEqual(result.passes, 1)
                self.assertEqual(result.stdout, b'')

    def test_version_failure_prevents_formatting(self):
        result = self.check_scope(version_code=2)
        self.assertEqual(result.exit_code, 2)
        self.assertEqual(result.passes, 0)
        self.assertEqual(result.stdout, b'')

    def test_relative_executable_is_resolved_before_changing_directory(self):
        result = self.check_scope(tool='./formatter')
        self.assertEqual(result.exit_code, 0)
        self.assertTrue(Path(result.calls[0][0]).is_absolute())
        self.assertEqual(result.calls[0][0], result.calls[-1][0])


if __name__ == '__main__':
    unittest.main()
